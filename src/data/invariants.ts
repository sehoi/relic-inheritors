/**
 * 조합 훑기 측정 지점.
 *
 * **파티 Lv20 vs 잡몹 Lv40.** 레벨 차가 크게 벌어져 보이지만, 이 지점을 고른 이유는
 * 게임이 여기서 균형 잡혀 있다고 보아서가 아니라 **여기서만 승률이 갈리기 때문이다.**
 * 전부 이기거나 전부 지는 구간에서는 불변식이 측정 자체를 못 한다.
 *
 * 실측(유물 12종, 슬롯을 채우는 조합 495개 중 120개, 시드 300):
 *
 * ```
 * 적 Lv39  격차  0.7%p  밴드  33%  필수도  0.3%p   최고 100% 최저 51%   ← 밴드 미달
 * 적 Lv40  격차  2.7%p  밴드  55%  필수도  2.7%p   최고 100% 최저 25%   ✓ 여기
 * 적 Lv41  격차  7.7%p  밴드  53%  필수도  8.3%p   최고 100% 최저  8%   ✓
 * 적 Lv42  격차 18.0%p  밴드  32%  필수도 18.0%p   최고  98% 최저  2%   ← 밴드 미달
 * 적 Lv43  격차 22.7%p  밴드  12%  필수도 22.7%p   최고  94% 최저  1%
 * ```
 *
 * **40~41 이 통과한다.** 지점 하나가 아니라 구간이 통과한다는 것이 중요하다 —
 * 한 레벨만 통과하면 그건 측정이 아니라 우연을 고른 것이다.
 *
 * ⚠️ **통과 구간이 좁아지고 있다.** 유물 7종일 때는 3개 레벨(39~41)이 통과했는데
 * 12종에서는 2개다. 유물이 늘수록 조합끼리 비슷해져 승률이 몰리기 때문이다.
 * 난이도 곡선이 가파른 것과 겹친 결과이며, 계속 좁아지면 측정 자체가 불안정해진다.
 *
 * **데이터를 고치면 측정 지점이 따라 움직인다.** T-035 에서 `잿빛 등` 의 최강 액티브를
 * 2단계로 잠그자 파티가 약해져 지점이 Lv42 → Lv40 으로 내려왔다.
 *
 * 보스전은 이 레벨대에서 승률이 전부 0% 라 조합을 가르지 못한다. 그래서 잡몹전으로 잰다.
 *
 * ⚠️ **시드 수가 판정을 바꾼다.** 유물 3종 시절, 시드 40으로 재면 격차 22%p 로 통과하고
 * 300으로 재면 26.7%p 로 실패했다 — 표본이 모자라 통과하는 불변식은 초록일 때 더 위험하다.
 * `tools/sim.ts` 와 같은 300을 쓴다.
 */
