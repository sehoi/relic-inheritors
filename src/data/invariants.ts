/**
 * 조합 훑기 측정 지점.
 *
 * **파티 Lv20 vs 잡몹 Lv32.** 레벨 차가 크게 벌어져 보이지만, 이 지점을 고른 이유는
 * 게임이 여기서 균형 잡혀 있다고 보아서가 아니라 **여기서만 승률이 갈리기 때문이다.**
 * 전부 이기거나 전부 지는 구간에서는 불변식이 측정 자체를 못 한다.
 *
 * 실측(파티 **2인**, 유물 12종, 조합 495개 중 120개, 시드 200):
 *
 * ```
 * 적 Lv31  격차  0.5%p  밴드  28%  필수도  0.5%p   최고 100% 최저 62%   ← 밴드 미달
 * 적 Lv32  격차  5.0%p  밴드  57%  필수도  5.5%p   최고 100% 최저 39%   ✓ 여기
 * 적 Lv33  격차 10.0%p  밴드  53%  필수도 13.0%p   최고 100% 최저 22%   ✓
 * 적 Lv34  격차 21.5%p  밴드  24%  필수도 22.0%p   최고  97% 최저 10%   ← 밴드 미달
 * ```
 *
 * **32~33 이 통과한다.** 지점 하나가 아니라 구간이 통과한다는 것이 중요하다 —
 * 한 레벨만 통과하면 그건 측정이 아니라 우연을 고른 것이다.
 *
 * ⚠️ **지점이 Lv40 → Lv32 로 내려왔다** (T-049a). 데이터가 아니라 **재는 대상**이 바뀌었다 —
 * 그전까지 시뮬레이터는 4인 파티를 쓰고 있었고, 게임은 2인이었다. 인원이 절반이면
 * 같은 적이 두 배로 어렵다. 그 시절 수치는 존재하지 않는 편성에 대한 것이었다.
 *
 * **통과 구간이 좁다** (2개 레벨). 유물이 늘수록 조합끼리 비슷해져 승률이 몰리고,
 * 난이도 곡선이 가파른 것과 겹친 결과다. 계속 좁아지면 측정 자체가 불안정해진다.
 *
 * 보스전은 이 레벨대에서 승률이 전부 0% 라 조합을 가르지 못한다. 그래서 잡몹전으로 잰다.
 *
 * ⚠️ **시드 수가 판정을 바꾼다.** 유물 3종 시절, 시드 40으로 재면 격차 22%p 로 통과하고
 * 300으로 재면 26.7%p 로 실패했다 — 표본이 모자라 통과하는 불변식은 초록일 때 더 위험하다.
 * `tools/sim.ts` 와 같은 300을 쓴다.
 */
