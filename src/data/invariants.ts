/**
 * 불변식 5 · 전투 길이 (GDD §5.5).
 *
 * **라운드 수는 파티 인원에 매인 단위다.** GDD 의 원래 값(잡몹 3~6, 보스 12~25)은
 * 파티가 4인이라고 가정하고 쓰였는데, 실제 게임은 2인이었다 (T-049a 에서 드러났다).
 * 인원이 절반이면 같은 적을 잡는 데 라운드가 두 배로 든다 — 게임이 달라진 게 아니라
 * 자가 달라진 것이다.
 *
 * 그래서 **비율**을 함께 둔다. 보스전이 잡몹전보다 확실히 길다는 것은 인원이 바뀌어도
 * 뜻이 변하지 않는다. 그 예상대로 됐다 — T-049b 에서 인원이 4인이 되며 절대값은 전부
 * 다시 쟀지만 비율은 손대지 않았다.
 *
 * **그리고 GDD 의 원래 값이 그대로 맞는 값이 되었다.** 4인을 가정하고 쓰인 3~6 / 12~25 가,
 * 파티가 실제로 4인이 되자 실측과 맞아떨어진다. T-049a 에서 8 / 9~25 로 늘려 잡았던 것은
 * 게임을 고친 게 아니라 자를 인원에 맞춰 늘린 것이었고, 이제 그 보정이 필요 없다.
 *
 * 실측(파티 4인, 시드 100): 잡몹 3.1~3.5 라운드, 보스 14.8~19.9, 비율 4.2~4.9.
 * 공격 편향 편성은 잡몹 2.1.
 */
